PROTOCOL_PATH = REPO_ROOT / "doc" / "experiment-minimum-context.md"


def test_protocol_records_the_full_grid_amendment():
    """A formal requirement, not a nicety: the adaptive ladder is part of the
    pre-registered protocol, so withdrawing it is an amendment (SS12). Code
    review cannot catch a missing one -- nothing in the driver points at it."""
    text = PROTOCOL_PATH.read_text(encoding="utf-8")
    amendments = text.split("## 12. Amendments", 1)[1]
    rows = [ln for ln in amendments.splitlines() if ln.startswith("| 2026-08-22")]
    assert rows, "no 2026-08-22 amendment row in SS12"
    assert any("grid" in r.lower() for r in rows)

    section = text.split("### 7.3", 1)[1].split("### 7.4", 1)[0]
    assert "2026-08-22" in section
    assert "exhaustively" in section

    # The old rule may still appear, but only as history: the section quotes what
    # it replaced, and that quote must stay inside the italicised amendment note.
    historical = section.split("*", 2)[1] if section.count("*") >= 2 else ""
    assert "stop as soon as" not in section.replace(historical, "")


