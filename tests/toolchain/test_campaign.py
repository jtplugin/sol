def _full_ladder_plan(cell="c1", mode="m1", queue="q1"):
    return [
        {"cell": cell, "mode": mode, "rendering": lvl, "queue": queue, "rep": rep, "status": "pending"}
        for lvl in campaign_mod.RENDERINGS for rep in (1, 2, 3)
    ]


def test_run_rows_executes_every_rendering_even_when_l0_scores_high(monkeypatch):
    """The reverse of the pre-2026-08-22 assertion. A cell that clears 0.99 at
    L0 must still be measured at every other rendering: whether fidelity stays
    above threshold as L grows -- and how prose compares (SS5.4) -- is the
    question, not the stopping rule."""
    calls = []

    def fake_execute_row(row, cell, mode, level, queue_id, *a, **k):
        calls.append((level, row["rep"]))
        row["status"] = "done"
        return _FakeScore(0.99 if level == "L0" else 0.0)

    monkeypatch.setattr(campaign_mod, "_execute_row", fake_execute_row)
    monkeypatch.setattr(campaign_mod, "_save_plan", lambda plan: None)

    plan = _full_ladder_plan()
    campaign_mod._run_rows({"cell": "c1"}, "m1", "q1", plan, None, {}, {}, {})

    assert [lvl for lvl, _rep in calls] == [lvl for lvl in campaign_mod.RENDERINGS for _ in (1, 2, 3)]
    assert len(calls) == 3 * len(campaign_mod.RENDERINGS) == 21
    assert all(r["status"] == "done" for r in plan)


def test_run_rows_saves_plan_after_every_single_run(monkeypatch):
    """FR-14 unchanged: an interruption never loses more than the run in flight."""
    saves = []

    def fake_execute_row(row, cell, mode, level, queue_id, *a, **k):
        row["status"] = "done"
        return _FakeScore(0.10)

    monkeypatch.setattr(campaign_mod, "_execute_row", fake_execute_row)
    monkeypatch.setattr(campaign_mod, "_save_plan", lambda plan: saves.append(len(
        [r for r in plan if r["status"] == "done"])))

    plan = _full_ladder_plan()
    campaign_mod._run_rows({"cell": "c1"}, "m1", "q1", plan, None, {}, {}, {})

    assert saves == list(range(1, 3 * len(campaign_mod.RENDERINGS) + 1))


