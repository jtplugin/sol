def _install_fake_mode(monkeypatch, tmp_path):
    monkeypatch.setattr(campaign_mod, "INDEX_PATH", tmp_path / "index.jsonl")
    monkeypatch.setattr(campaign_mod, "_mode_config", lambda mode: {
        "model": "model-x", "backend": "openai", "reasoning_budget": 0,
        "key": "", "url": "http://x", "temperature": 0.2, "thinking": None,
        "ctx_size": 1000, "kv_cache_type": "q8_0", "n_parallel": 1,
    })


def _write_index(tmp_path, n):
    row = {
        "fixture_id": campaign_mod.SUPPORT_INTAKE_FIXTURE_ID,
        "staged_input_id": "queue-01", "context": "E0", "model_id": "model-x",
        "spec_version": campaign_mod.SPEC_VERSION, "backend": "openai",
        "reasoning_budget": 0, "process_rendering": "L1",
        # the coordinate carries the mode since 2026-08-23: without it two
        # modes on the same gguf credit each other's runs
        "mode": "m1",
        "status": "done",
    }
    (tmp_path / "index.jsonl").write_text(
        "".join(json.dumps(row) + "\n" for _ in range(n)), encoding="utf-8")


def _three_reps(status_of_rep1="pending"):
    return [
        {"cell": "c1", "mode": "m1", "rendering": "L1", "queue": "queue-01", "rep": rep,
         "status": status_of_rep1 if rep == 1 else "pending"}
        for rep in (1, 2, 3)
    ]


def test_resume_does_not_credit_an_already_counted_index_entry(tmp_path, monkeypatch):
    """The 2026-08-22 kill mid-smoke exposed this: rep=1 is done in the plan AND
    has its index entry. Crediting that entry again would mark rep=2 done without
    ever running it."""
    _install_fake_mode(monkeypatch, tmp_path)
    _write_index(tmp_path, 1)

    plan = _three_reps(status_of_rep1="done")
    campaign_mod._reconcile_with_index(plan)

    assert [r["status"] for r in plan] == ["done", "pending", "pending"]


def test_resume_credits_only_the_surplus_index_entries(tmp_path, monkeypatch):
    """Two runs in the index, one of them already recorded in the plan: exactly
    one pending row is owed a credit, not two."""
    _install_fake_mode(monkeypatch, tmp_path)
    _write_index(tmp_path, 2)

    plan = _three_reps(status_of_rep1="done")
    campaign_mod._reconcile_with_index(plan)

    assert [r["status"] for r in plan] == ["done", "done", "pending"]


def test_resume_ignores_error_rows_when_counting_consumption(tmp_path, monkeypatch):
    """An 'error' row spent a run but produced no 'done' index entry, so it must
    not consume one either."""
    _install_fake_mode(monkeypatch, tmp_path)
    _write_index(tmp_path, 1)

    plan = _three_reps()
    plan[0]["status"] = "error"
    campaign_mod._reconcile_with_index(plan)

    assert [r["status"] for r in plan] == ["error", "done", "pending"]


