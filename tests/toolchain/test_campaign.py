    mancanti = [
        (cell["cell"], cell["gguf"])
        for cell in campaign_mod._load_cells()
        if not (AI_MODELS_DIR / cell["gguf"]).is_file()
    ]
    assert not mancanti, f"gguf dichiarati ma assenti in {AI_MODELS_DIR}: {mancanti}"


