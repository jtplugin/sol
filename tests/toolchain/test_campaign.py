    monkeypatch.setattr(campaign_mod, "PLAN_PATH", plan_path)
    monkeypatch.setattr(campaign_mod, "_use_results_root", lambda *a, **k: None)

    with pytest.raises(SystemExit) as exc:
        campaign_mod.cmd_plan(argparse.Namespace(force=False))

    assert "3 rows already run" in str(exc.value)
    assert json.loads(plan_path.read_text(encoding="utf-8")) == rows   # untouched


